# STEERING LATENCY PREDICTION
# =============================================================================

def predict_control_pose(
    position,
    yaw,
    speed,
    yaw_rate,
    prediction_distance_cap
):
    """
    Predict ONLY the steering pose.

    Speed-profile indexing always stays tied to the current global
    localization position.

    The measured actuator time delay is used, but the geometric prediction is
    capped because the offline /1.15 replay showed that removing the turn-in
    gate while retaining this cap closely reproduces the older IPS controller.
    """

    if speed <= 1e-6:

        return (
            position.copy(),
            yaw,
            0.0
        )

    prediction_time = (
        STEERING_LATENCY_COMP
    )

    prediction_time = min(
        prediction_time,
        prediction_distance_cap
        /
        max(
            abs(speed),
            1e-6
        )
    )

    prediction_distance = (
        abs(speed)
        *
        prediction_time
    )

    if abs(
        yaw_rate
    ) < 1e-4:

        predicted_position = np.array([
            position[0]
            +
            speed
            *
            prediction_time
            *
            math.cos(yaw),

            position[1]
            +
            speed
            *
            prediction_time
            *
            math.sin(yaw)
        ])

        return (
            predicted_position,
            yaw,
            prediction_distance
        )

    predicted_yaw = wrap_angle(
        yaw
        +
        yaw_rate
        *
        prediction_time
    )

    radius = (
        speed
        /
        yaw_rate
    )

    predicted_position = np.array([
        position[0]
        +
        radius
        *
        (
            math.sin(
                predicted_yaw
            )
            -
            math.sin(
                yaw
            )
        ),

        position[1]
        -
        radius
        *
        (
            math.cos(
                predicted_yaw
            )
            -
            math.cos(
                yaw
            )
        )
    ])

    return (
        predicted_position,
        predicted_yaw,
        prediction_distance
    )


