def speed_curvature_at_index(
    index
):
    """
    Robust local curvature around one future speed-profile waypoint.
    """

    idx = int(
        index
    ) % path_len

    max_curvature = 0.0

    for offset in range(
        -CURVATURE_SPEED_HALF_WINDOW,
        CURVATURE_SPEED_HALF_WINDOW + 1
    ):

        kappa = abs(
            float(
                path_curvature[
                    (idx + offset) % path_len
                ]
            )
        )

        if kappa > max_curvature:
            max_curvature = kappa

    return max_curvature


def curvature_speed_divisor(
    curvature,
    fast_divisor=VELOCITY_DIVISOR
):
    """
    Straight/gentle:
        divisor = 1.15

    Extreme/tight:
        divisor = 1.50

    Smooth interpolation between them.
    """

    denominator = (
        CURVATURE_DIVISOR_FULL
        -
        CURVATURE_DIVISOR_START
    )

    if denominator <= 1e-9:
        return TIGHT_CORNER_DIVISOR

    blend = np.clip(
        (
            curvature
            -
            CURVATURE_DIVISOR_START
        )
        /
        denominator,
        0.0,
        1.0
    )

    return float(
        fast_divisor
        +
        blend
        *
        (
            TIGHT_CORNER_DIVISOR
            -
            fast_divisor
        )
    )


