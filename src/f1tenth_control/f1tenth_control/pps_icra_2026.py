def wrap_angle(angle):

    return math.atan2(
        math.sin(angle),
        math.cos(angle)
    )


def quaternion_to_yaw(q):

    siny_cosp = 2.0 * (
        q.w * q.z
        +
        q.x * q.y
    )

    cosy_cosp = 1.0 - 2.0 * (
        q.y * q.y
        +
        q.z * q.z
    )

    return math.atan2(
        siny_cosp,
        cosy_cosp
    )


