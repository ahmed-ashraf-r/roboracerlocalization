def wrapped_indices(
    center_idx,
    behind,
    ahead
):

    return np.array([
        (center_idx + offset) % path_len
        for offset in range(
            -behind,
            ahead + 1
        )
    ], dtype=int)


def update_nearest_path_index(
    position,
    previous_idx
):
    """
    Find the nearest waypoint only on the local racing-line branch.

    This is intentionally monotonic/local rather than a full-path global
    nearest-point search.
    """

    indices = wrapped_indices(
        previous_idx,
        NEAREST_SEARCH_BEHIND,
        NEAREST_SEARCH_AHEAD
    )

    points = goal[
        indices
    ]

    distances = np.linalg.norm(
        points - position,
        axis=1
    )

    return int(
        indices[
            int(
                np.argmin(
                    distances
                )
            )
        ]
    )


def advance_path_index_by_distance(
    start_idx,
    distance_m
):
    """
    Walk forward along path ARC LENGTH.
    """

    idx = int(
        start_idx
    ) % path_len

    travelled = 0.0

    for _ in range(path_len):

        if travelled >= distance_m:
            break

        next_idx = (
            idx + 1
        ) % path_len

        travelled += float(
            np.linalg.norm(
                goal[next_idx]
                -
                goal[idx]
            )
        )

        idx = next_idx

    return idx


def find_steering_lookahead_index(
    start_idx,
    position,
    desired_distance
):
    """
    Search FORWARD on the current branch and return the first waypoint whose
    Euclidean distance from the steering pose reaches the requested lookahead.

    This reproduces the useful geometry of the team's older successful
    controller without using IPS.
    """

    idx = int(
        start_idx
    ) % path_len

    for _ in range(path_len):

        distance = np.linalg.norm(
            goal[idx]
            -
            position
        )

        if distance >= desired_distance:
            return idx

        idx = (
            idx + 1
        ) % path_len

    return idx


