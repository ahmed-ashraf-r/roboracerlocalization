def signed_cross_track_error(
    position,
    nearest_idx
):
    """
    Signed lateral distance from the local racing-line tangent.

    Positive = vehicle is left of the path tangent.
    Negative = vehicle is right of the path tangent.
    """

    previous_idx = (
        nearest_idx - 1
    ) % path_len

    next_idx = (
        nearest_idx + 1
    ) % path_len

    tangent = (
        goal[next_idx]
        -
        goal[previous_idx]
    )

    tangent_norm = float(
        np.linalg.norm(
            tangent
        )
    )

    if tangent_norm < 1e-9:
        return 0.0

    tangent = (
        tangent
        /
        tangent_norm
    )

    error_vector = (
        position
        -
        goal[
            nearest_idx
        ]
    )

    return float(
        tangent[0]
        *
        error_vector[1]
        -
        tangent[1]
        *
        error_vector[0]
    )


def inside_corner_error(
    position,
    nearest_idx
):
    """
    Return only the component that means the vehicle is cutting toward the
    INSIDE of the current bend.

    For a left bend:
        left-of-path error is inside.

    For a right bend:
        right-of-path error is inside.
    """

    kappa = float(
        path_signed_curvature[
            nearest_idx
        ]
    )

    if abs(
        kappa
    ) < CUT_GUARD_MIN_CURVATURE:

        return 0.0

    cross_track = (
        signed_cross_track_error(
            position,
            nearest_idx
        )
    )

    inside = (
        cross_track
        *
        (
            1.0
            if kappa > 0.0
            else -1.0
        )
    )

    return max(
        0.0,
        float(
            inside
        )
    )


def outward_path_normal(
    nearest_idx
):
    """
    Unit normal pointing OUTSIDE the current bend.
    """

    previous_idx = (
        nearest_idx - 1
    ) % path_len

    next_idx = (
        nearest_idx + 1
    ) % path_len

    tangent = (
        goal[next_idx]
        -
        goal[previous_idx]
    )

    tangent_norm = float(
        np.linalg.norm(
            tangent
        )
    )

    if tangent_norm < 1e-9:

        return np.zeros(
            2,
            dtype=float
        )

    tangent = (
        tangent
        /
        tangent_norm
    )

    left_normal = np.array([
        -tangent[1],
        tangent[0]
    ])

    kappa = float(
        path_signed_curvature[
            nearest_idx
        ]
    )

    if kappa > 0.0:

        # Left turn -> outside is right.
        return (
            -left_normal
        )

    if kappa < 0.0:

        # Right turn -> outside is left.
        return (
            left_normal
        )

    return np.zeros(
        2,
        dtype=float
    )


